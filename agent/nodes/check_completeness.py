"""
agent/nodes/check_completeness.py
Node: check_completeness

Responsibility:
  Deterministic check of whether enough information has been gathered to
  proceed with a search or submission. No LLM involved.

  For MISSING_CHILD: requires gender + (age.exact OR age.min OR age.max) + last_seen_location
  For FOUND_CHILD:   requires found_location

  Builds the missing_information list and a natural-language followup_question.

  followup_question is generated by the LLM (Phase 6) or a template fallback (Phase 5).
  It targets at most the two most impactful missing fields per turn.

Inputs consumed:
  state.intent, state.child_search_criteria, state.found_child_report

Outputs produced:
  missing_information  — list of field name strings
  followup_question    — natural-language question string, or None if complete

Phase 5 status: FULL IMPLEMENTATION (deterministic — no LLM for the logic).
  followup_question generation uses a template; LLM will improve it in Phase 6.
"""

from __future__ import annotations

import logging

from agent.dependencies import get_llm
from agent.state import Intent, WayfindState
from schemas.child import ChildSearchCriteria, FoundChildReport

logger = logging.getLogger(__name__)

# ── Minimum required fields ────────────────────────────────────────────────────
_REGISTER_CHILD_REQUIRED = {"name", "gender", "age"}
_MISSING_CHILD_REQUIRED  = {"gender", "age", "last_seen_location"}
_FOUND_CHILD_REQUIRED    = {"found_location"}

# ── Human-readable labels for follow-up questions ─────────────────────────────
_FIELD_LABELS: dict[str, str] = {
    "name":                 "the child's full name",
    "gender":               "the child's gender",
    "age":                  "approximately how old the child is",
    "city":                 "your home city or residential area",
    "identifying_features": "any distinguishing birthmarks or physical features",
    "medical_notes":        "any medical conditions or allergy notes",
    "last_seen_location":   "where the child was last seen",
    "found_location":       "where you found the child",
    "clothing":             "what the child was wearing",
    "hair_color":           "the child's hair colour",
}


async def check_completeness(state: WayfindState) -> dict:
    """Determine which required fields are still missing and build a follow-up question."""
    intent = state.get("intent")
    missing: list[str] = []

    if intent == Intent.REGISTER_CHILD:
        reg = state.get("child_registration_data")
        missing = _check_register_child(reg)

    elif intent == Intent.MISSING_CHILD:
        criteria = state.get("child_search_criteria")
        missing = _check_missing_child(criteria)

    elif intent == Intent.FOUND_CHILD:
        report = state.get("found_child_report")
        missing = _check_found_child(report)

    else:
        # SHELTER_SEARCH / GUIDANCE / CASE_STATUS / UNKNOWN — no completeness check needed
        return {"missing_information": [], "followup_question": None}

    if not missing:
        logger.info(
            "Session %s: completeness OK for intent=%s",
            state.get("session_id"), intent.value if hasattr(intent, "value") else (str(intent) if intent else "none"),
        )
        return {"missing_information": [], "followup_question": None}

    # Limit to max 2 fields per follow-up turn to avoid overwhelming the user
    priority_missing = missing[:2]

    # Try LLM-generated natural language follow-up question
    question: str | None = None
    llm = get_llm()
    if llm is not None:
        try:
            question = await llm.generate_followup_question(
                missing_fields=priority_missing,
                context=state.get("conversation_history", []),
            )
        except Exception as exc:
            logger.warning("LLM generate_followup_question failed, using template: %s", exc)

    if not question:
        question = _build_followup_question(priority_missing, intent)

    logger.info(
        "Session %s: missing=%s → followup generated",
        state.get("session_id"), priority_missing,
    )

    return {
        "missing_information": missing,
        "followup_question": question,
    }


# ── Completeness checkers ──────────────────────────────────────────────────────

def _check_register_child(reg: Any) -> list[str]:
    """Return list of missing required field names for peacetime child pre-registration."""
    if reg is None:
        return ["name", "gender", "age", "city", "identifying_features"]

    if isinstance(reg, dict):
        has_name = bool(reg.get("name"))
        has_gender = bool(reg.get("gender"))
        age = reg.get("age") or {}
        has_age = bool(age.get("exact") or age.get("min") or age.get("max")) if isinstance(age, dict) else bool(reg.get("age"))
    else:
        has_name = bool(getattr(reg, "name", None))
        has_gender = bool(getattr(reg, "gender", None))
        age_obj = getattr(reg, "age", None)
        has_age = bool(
            age_obj and (age_obj.exact is not None or age_obj.min is not None or age_obj.max is not None)
        )

    missing = []
    if not has_name:
        missing.append("name")
    if not has_gender:
        missing.append("gender")
    if not has_age:
        missing.append("age")
    return missing


def _check_missing_child(criteria: ChildSearchCriteria | dict | None) -> list[str]:
    """Return list of missing required field names for a MISSING_CHILD search."""
    if criteria is None:
        return list(_MISSING_CHILD_REQUIRED)

    if isinstance(criteria, dict):
        c = criteria
        has_gender = bool(c.get("gender"))
        age = c.get("age") or {}
        has_age = bool(age.get("exact") or age.get("min") or age.get("max"))
        has_location = bool(c.get("last_seen_location"))
    else:
        has_gender   = bool(criteria.gender)
        has_age      = bool(
            criteria.age.exact is not None
            or criteria.age.min is not None
            or criteria.age.max is not None
        )
        has_location = bool(criteria.last_seen_location)

    missing = []
    if not has_gender:
        missing.append("gender")
    if not has_age:
        missing.append("age")
    if not has_location:
        missing.append("last_seen_location")
    return missing


def _check_found_child(report: FoundChildReport | dict | None) -> list[str]:
    """Return list of missing required field names for a FOUND_CHILD report."""
    if report is None:
        return list(_FOUND_CHILD_REQUIRED)

    loc = report.get("found_location") if isinstance(report, dict) else report.found_location

    missing = []
    if not loc or loc == "unknown":
        missing.append("found_location")
    return missing


# ── Follow-up question builder ─────────────────────────────────────────────────

def _build_followup_question(missing_fields: list[str], intent: Intent | None) -> str:
    """Build a natural-language follow-up question for the missing fields.

    Phase 5: Template-based.
    Phase 6: Replace with LLM call:
        llm = get_llm()
        return await llm.generate_followup_question(missing_fields, context)
    """
    labels = [_FIELD_LABELS.get(f, f.replace("_", " ")) for f in missing_fields]

    if len(labels) == 1:
        return f"Could you tell me {labels[0]}?"
    elif len(labels) == 2:
        return f"Could you tell me {labels[0]} and {labels[1]}?"
    else:
        joined = ", ".join(labels[:-1]) + f", and {labels[-1]}"
        return f"Could you tell me {joined}?"
